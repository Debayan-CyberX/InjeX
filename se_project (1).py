def char_substitution(text):
    """
    Replace selected characters with visually similar characters.
    """

    substitutions = {
        "a": ["@", "ɑ"],
        "e": ["3", "е"],
        "i": ["1", "і"],
        "o": ["0", "ο"],
        "s": ["$", "ѕ"],
        "t": ["7"]
    }

    chars = list(text)

    indices = list(range(len(chars)))
    random.shuffle(indices)

    changes = max(1, int(len(chars) * 0.04))

    changed = 0

    for i in indices:

        char = chars[i].lower()

        if char in substitutions:
            chars[i] = random.choice(substitutions[char])
            changed += 1

        if changed >= changes:
            break

    return "".join(chars)

def spacing_obfuscation(text):

    words = text.split()

    new_words = []

    for word in words:

        if len(word) > 5 and random.random() < 0.35:

            split_point = len(word) // 2

            word = (
                word[:split_point]
                + " "
                + word[split_point:]
            )

        new_words.append(word)

    return " ".join(new_words)

def punctuation_obfuscation(text):

    replacements = {
        "ignore": "ignore...",
        "previous": "previous!!!",
        "instruction": "instruction???",
        "system": "system::",
        "prompt": "prompt---"
    }

    result = text

    for old, new in replacements.items():

        if random.random() < 0.5:

            result = re.sub(
                rf"\b{old}\b",
                new,
                result,
                flags=re.IGNORECASE
            )

    return result

def instruction_splitting(text):

    words = text.split()

    if len(words) < 4:
        return text

    output = []

    for word in words:

        if len(word) >= 6 and random.random() < 0.25:

            mid = len(word) // 2

            output.append(
                word[:mid] + " " + word[mid:]
            )

        else:
            output.append(word)

    return " ".join(output)

def unicode_obfuscation(text):

    mapping = {
        "a": "а",
        "c": "с",
        "e": "е",
        "o": "о",
        "p": "р",
        "x": "х"
    }

    chars = list(text)

    for i in range(len(chars)):

        char = chars[i].lower()

        if char in mapping and random.random() < 0.08:

            chars[i] = mapping[char]

    return "".join(chars)

def adversarial_transform(text):

    transformations = [
        char_substitution,
        spacing_obfuscation,
        punctuation_obfuscation,
        instruction_splitting,
        unicode_obfuscation
    ]

    selected = random.sample(
        transformations,
        random.randint(2, 4)
    )

    result = text

    for transform in selected:
        result = transform(result)

    return result

